import { copyFileSync, mkdtempSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { execFileSync } from 'node:child_process';

const directory = dirname(fileURLToPath(import.meta.url));
const root = resolve(directory, '../../..');
const temporary = mkdtempSync(join(tmpdir(), 'aigasapi-plugin-'));
try {
  execFileSync('go', ['run', './integrations/newapi/aigasapi', temporary], { cwd: root, stdio: 'inherit' });
  copyFileSync(join(directory, 'adapter.js'), join(temporary, 'adapter.js'));
  const result = await Bun.build({
    entrypoints: [join(temporary, 'adapter.js')], target: 'browser', format: 'esm', minify: false,
  });
  if (!result.success || result.outputs.length !== 1) throw new Error('Expected one standalone plugin');
  const source = (await result.outputs[0].text()).replace(/^\/\/ .*\/aigasapi-plugin-[^/]+\//gm, '// aigasapi/');
  writeFileSync(join(directory, 'aigasapi-video-2.0.3.js'), '// Generated by bun integrations/newapi/aigasapi/build.mjs.\n' + source);
  for (const name of ['contract.json', 'model-mapping.json', 'contract-dry-run.json']) {
    copyFileSync(join(temporary, name), join(directory, name));
  }
} finally {
  rmSync(temporary, { recursive: true, force: true });
}
