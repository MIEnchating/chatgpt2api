import { copyFileSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { execFileSync } from 'node:child_process';

const directory = dirname(fileURLToPath(import.meta.url));
const root = resolve(directory, '../../..');
const temporary = mkdtempSync(join(tmpdir(), 'hirun-plugin-'));
try {
  execFileSync('go', ['run', './integrations/newapi/hirun/generate.go', temporary], { cwd: root, stdio: 'inherit' });
  copyFileSync(join(temporary, 'hirun-video-1.0.2.js'), join(temporary, 'core.js'));
  copyFileSync(join(directory, 'adapter.js'), join(temporary, 'adapter.js'));
  const result = await Bun.build({ entrypoints: [join(temporary, 'adapter.js')], target: 'browser', format: 'esm', minify: false });
  if (!result.success) throw new Error(result.logs.join('\n'));
  if (result.outputs.length !== 1) throw new Error('Expected a standalone plugin');
  const source = (await result.outputs[0].text()).replace(/^\/\/ .*\/hirun-plugin-[^/]+\/(core\.js|adapter\.js)$/gm, '// hirun/$1');
  writeFileSync(join(directory, 'hirun-video-1.0.2.js'), '// Generated by bun integrations/newapi/hirun/build.mjs. No API keys are embedded.\n' + source);
  copyFileSync(join(temporary, 'contract-dry-run.json'), join(directory, 'contract-dry-run.json'));
} finally {
  rmSync(temporary, { recursive: true, force: true });
}
