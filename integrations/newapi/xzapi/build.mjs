import { mkdtempSync, readFileSync, writeFileSync, copyFileSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join, dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { execFileSync } from 'node:child_process';

const directory = dirname(fileURLToPath(import.meta.url));
const root = resolve(directory, '../../..');
const temporary = mkdtempSync(join(tmpdir(), 'xzapi-plugin-'));
try {
  execFileSync('go', ['run', './integrations/newapi/xzapi/generate.go', temporary], { cwd: root, stdio: 'inherit' });
  copyFileSync(join(directory, 'adapter.js'), join(temporary, 'adapter.js'));
  const result = await Bun.build({ entrypoints: [join(temporary, 'adapter.js')], target: 'browser', format: 'cjs', minify: false });
  if (!result.success) throw new Error(result.logs.join('\n'));
  if (result.outputs.length !== 1) throw new Error('Expected a standalone plugin');
  const source = (await result.outputs[0].text()).replace(/^\s*\/\/ .*\/xzapi-plugin-[^/]+\/(generated\.js|adapter\.js)$/gm, '// xzapi/$1');
  const exports = ['meta', 'protocols', 'extractUsage', 'parseSubmitResponse', 'buildQueryRequest', 'parseTaskResult', 'listArtifacts', 'buildSubmitRequest', 'buildContentRequest']
    .map(name => `export const ${name} = xzapiPlugin.${name};`).join('\n');
  writeFileSync(join(directory, 'xzapi-video-1.1.0.js'), '// Generated by bun integrations/newapi/xzapi/build.mjs. No API keys are embedded.\n' + 'const xzapiPlugin = (() => {\nconst module = { exports: {} };\n' + source + '\nreturn module.exports;\n})();\n' + exports + '\n');
  writeFileSync(join(directory, 'contract-dry-run.json'), readFileSync(join(temporary, 'contract-dry-run.json')));
  console.log('Generated xzapi-video-1.1.0.js with embedded contracts.');
} finally {
  rmSync(temporary, { recursive: true, force: true });
}
