import { mkdtempSync, readFileSync, writeFileSync, copyFileSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join, dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { execFileSync } from 'node:child_process';

const directory = dirname(fileURLToPath(import.meta.url));
const root = resolve(directory, '../../..');
const temporary = mkdtempSync(join(tmpdir(), 'openai-fit-minimax-plugin-'));
try {
  execFileSync('go', ['run', './integrations/newapi/openai-fit-minimax/generate.go', temporary], { cwd: root, stdio: 'inherit' });
  copyFileSync(join(directory, 'adapter.js'), join(temporary, 'adapter.js'));
  const result = await Bun.build({ entrypoints: [join(temporary, 'adapter.js')], target: 'browser', format: 'esm', minify: false });
  if (!result.success) throw new Error(result.logs.join('\n'));
  if (result.outputs.length !== 1) throw new Error('Expected a standalone plugin');
  const source = (await result.outputs[0].text()).replace(/^\/\/ .*\/openai-fit-minimax-plugin-[^/]+\/(group-\d+\.js|adapter\.js)$/gm, '// openai-fit-minimax/$1');
  writeFileSync(join(directory, 'openai-fit-minimax-video-1.2.0.js'), '// Generated by bun integrations/newapi/openai-fit-minimax/build.mjs. No API keys are embedded.\n' + source);
  writeFileSync(join(directory, 'contract-dry-run.json'), readFileSync(join(temporary, 'contract-dry-run.json')));
  console.log('Generated openai-fit-minimax-video-1.2.0.js with one embedded upstream contract.');
} finally {
  rmSync(temporary, { recursive: true, force: true });
}
